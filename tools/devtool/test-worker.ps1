# `dev test [-R <regex>]` runner: builds only the targets behind the selected
# CTest entries in the shared Ninja development tree, then runs them.
# `--coverage` does the same in a gcov-instrumented tree beside it and writes
# a line/branch report per layer (docs/workflow/build.md).
[CmdletBinding()]
param(
    # CTest name regex. Empty selects every registered test.
    [string]$Regex = '',
    # CTest label (e.g. core); its tests are added to the ones the regex selects.
    [string]$Label = '',
    # QtTest functions to run; requires the regex to select exactly one test.
    [string[]]$Function = @(),
    # Run the selection this many times, stopping at the first failure.
    [ValidateRange(1, 1000)]
    [int]$Repeat = 1,
    [ValidateSet('Debug', 'Release', 'RelWithDebInfo', 'MinSizeRel')]
    [string]$Configuration = 'Debug',
    [int]$Jobs = 0,
    [switch]$Configure,
    # Build the selected test targets but do not run them.
    [switch]$BuildOnly,
    # Print the selected tests and their build targets, then exit.
    [switch]$List,
    # Build and run in the instrumented <build>\coverage tree, then report.
    [switch]$Coverage
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

. (Join-Path $PSScriptRoot '..\toolchain.ps1')

$root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$build = Resolve-SpanTuiBuildDirectory -Root $root
$configureArgs = @()
if ($Coverage) {
    # Instrumented objects never mix with the development tree's.
    $build = Join-Path $build 'coverage'
    $configureArgs = @('-DSPANTUI_COVERAGE=ON')
}
$appName = 'SpanTui-test'

$toolchain = Resolve-SpanTuiToolchain
Use-SpanTuiToolchainPath $toolchain

# gcovr lives in a virtual environment under .dev\tools (or on PATH); its
# absence is reported before anything is built.
$gcovr = ''
if ($Coverage) {
    $gcovr = Join-Path $root '.dev\tools\gcovr\Scripts\gcovr.exe'
    if (-not (Test-Path -LiteralPath $gcovr)) {
        $found = Get-Command gcovr -ErrorAction SilentlyContinue
        $gcovr = if ($found) { $found.Source } else { '' }
    }
    if (-not $gcovr) {
        Fail ('gcovr not found. Install it once: python -m venv .dev\tools\gcovr; ' +
              '.dev\tools\gcovr\Scripts\python -m pip install gcovr')
    }
}

Initialize-SpanTuiBuildTree -Toolchain $toolchain -SourceDir $root -BuildDir $build `
    -BuildType $Configuration -ExtraArgs $configureArgs -Force:$Configure

# CTest's registry is generated by CMake. Bring build.ninja up to date first
# (a no-op unless a CMakeLists changed) so newly registered tests are seen.
Invoke-SpanTuiBuild -Toolchain $toolchain -BuildDir $build -Target 'build.ninja' -Jobs $Jobs

$selector = @()
if (-not $Label -and -not [string]::IsNullOrWhiteSpace($Regex)) { $selector = @('-R', $Regex) }

# CTest's JSON model names each test's command; a command that is an image in
# the build tree maps back to the target that produces it; any other command
# needs no build step.
$json = & $toolchain.CTest --test-dir $build -N --show-only=json-v1 @selector
if ($LASTEXITCODE -ne 0) { Fail 'Could not enumerate CTest entries.' }
$model = ($json -join "`n") | ConvertFrom-Json
$tests = @($model.tests)
if ($Label) {
    # CTest would AND -L with -R; here a label adds its tests to the regex's.
    # The union is then handed to CTest by exact name.
    $tests = @($tests | Where-Object {
        $labels = @(foreach ($property in @(if ($_.PSObject.Properties['properties']) { $_.properties })) {
            if ($property.name -eq 'LABELS') { $property.value }
        })
        ($labels -contains $Label) -or ($Regex -and $_.name -cmatch $Regex)
    })
    $selector = @('-R', ('^(' + (($tests | ForEach-Object { [regex]::Escape($_.name) }) -join '|') + ')$'))
}
if ($tests.Count -eq 0) {
    $shown = @(if ($Label) { "label $Label" }; if ($Regex) { $Regex })
    if ($shown.Count -eq 0) { $shown = @('<all>') }
    Fail "No CTest entries match $($shown -join ' or ')."
}

$buildRoot = [System.IO.Path]::GetFullPath($build).TrimEnd('\')
$targets = [System.Collections.Generic.List[string]]::new()
foreach ($test in $tests) {
    # CTest omits the command of a test whose image does not exist yet (a
    # newly registered test before its first build). The registration helpers
    # name every test after its executable target, so build that target.
    $command = @(if ($test.PSObject.Properties['command']) { $test.command })
    $image = if ($command.Count -gt 0) { [string]$command[0] } else { '' }
    $target = if ($command.Count -eq 0) { [string]$test.name } else { '' }
    if ($image) {
        $full = [System.IO.Path]::GetFullPath($image)
        $parent = (Split-Path -Parent $full).TrimEnd('\')
        if ($parent -ieq $buildRoot) {
            $stem = [System.IO.Path]::GetFileNameWithoutExtension($full)
            # The product image is emitted under its output name.
            $target = if ($stem -ieq $appName) { 'SpanTui' } else { $stem }
        }
    }
    if ($target -and -not $targets.Contains($target)) { $targets.Add($target) }
    if ($List) {
        $label = if ($target) { $target } else { '(script, no build)' }
        Write-Host ("  {0,-44} {1}" -f $test.name, $label)
    }
}
if ($List) { return }

# A test that runs a product image under another name has no target of its
# own; in a fresh tree its image is unknown, so build the default targets,
# which produce every product image.
$known = @(& $toolchain.CMake --build $build --target help |
    ForEach-Object { if ($_ -match '^([^:\s]+): ') { $Matches[1] } })
$unknown = @($targets | Where-Object { $known -notcontains $_ })
if ($unknown.Count -gt 0) {
    foreach ($name in $unknown) { [void]$targets.Remove($name) }
    $targets.Add('all')
}

# A function filter has to reach the test image as arguments, which CTest
# cannot forward; the image then runs directly under the environment CTest
# would have applied.
$functionImage = ''
$functionEnvironment = @()
if ($Function.Count -gt 0) {
    if ($tests.Count -ne 1) {
        Fail ("--function needs -R to select exactly one test; '{0}' selects {1}." -f $Regex, $tests.Count)
    }
    $only = $tests[0]
    $command = @(if ($only.PSObject.Properties['command']) { $only.command })
    $functionImage = if ($command.Count -gt 0) { [string]$command[0] } else { Join-Path $build "$($only.name).exe" }
    if ($command.Count -gt 1) { Fail "--function cannot be combined with test '$($only.name)', which passes its own arguments." }
    foreach ($property in @(if ($only.PSObject.Properties['properties']) { $only.properties })) {
        if ($property.name -eq 'ENVIRONMENT_MODIFICATION') { $functionEnvironment = @($property.value) }
    }
}

if ($targets.Count -gt 0) {
    if ($targets.Contains('SpanTui')) {
        # Windows cannot overwrite a running image; only this tree's test image.
        Stop-SpanTuiTestInstances -ExecutablePath (Join-Path $build "$appName.exe")
        Invoke-SpanTuiTimedStep 'Refresh product icon from SVG' {
            Invoke-SpanTuiBuild -Toolchain $toolchain -BuildDir $build `
                -Target 'spantui_brand_icon_refresh' -Jobs $Jobs
        }
    }
    Invoke-SpanTuiTimedStep ("Build {0} test target(s)" -f $targets.Count) {
        Invoke-SpanTuiBuild -Toolchain $toolchain -BuildDir $build -Target $targets.ToArray() -Jobs $Jobs
    }
}
if ($BuildOnly) {
    Write-Host 'TEST_BUILD_OK'
    return
}

# Tests write only below .dev\tmp\tests (CMakeLists.txt points each test's
# TEMP/TMP/APPDATA/LOCALAPPDATA at its own tests\<name>\ subdirectory there).
# Drop scratch that earlier runs left, then recreate every directory a
# selected test is pointed at: a missing TEMP fails each QTemporaryDir.
Get-ChildItem -LiteralPath (Get-SpanTuiDevPath -Name 'tmp\tests' -Root $root) -Force -ErrorAction SilentlyContinue |
    Remove-Item -Recurse -Force -ErrorAction SilentlyContinue
foreach ($test in $tests) {
    foreach ($property in @(if ($test.PSObject.Properties['properties']) { $test.properties })) {
        if ($property.name -ne 'ENVIRONMENT_MODIFICATION') { continue }
        foreach ($entry in @($property.value)) {
            if ($entry -match '^(TEMP|TMP|APPDATA|LOCALAPPDATA)=set:(.+)$') {
                New-Item -ItemType Directory -Force -Path $Matches[2] | Out-Null
            }
        }
    }
}
# Counters accumulate across runs; the report covers this run only.
if ($Coverage) {
    Get-ChildItem -LiteralPath $build -Recurse -Filter '*.gcda' -File -ErrorAction SilentlyContinue |
        Remove-Item -Force -ErrorAction SilentlyContinue
}

if ($functionImage) {
    # Same operations CTest supports for ENVIRONMENT_MODIFICATION, limited to
    # the ones the registration helpers use.
    foreach ($entry in $functionEnvironment) {
        if ($entry -notmatch '^([^=]+)=([a-z_]+):(.*)$') { Fail "Unsupported test environment entry: $entry" }
        $name, $operation, $value = $Matches[1], $Matches[2], $Matches[3]
        $current = [Environment]::GetEnvironmentVariable($name)
        $next = switch ($operation) {
            'set' { $value }
            'unset' { $null }
            'path_list_prepend' { if ($current) { "$value;$current" } else { $value } }
            'path_list_append' { if ($current) { "$current;$value" } else { $value } }
            default { Fail "Unsupported test environment operation: $operation" }
        }
        # PowerShell hands $null to a .NET string parameter as "", which would
        # leave an empty variable behind; git refuses an empty GIT_DIR, so
        # every git test skipped under --function.
        if ($null -eq $next) {
            Remove-Item -LiteralPath "Env:$name" -ErrorAction SilentlyContinue
        } else {
            [Environment]::SetEnvironmentVariable($name, $next)
        }
    }
    Invoke-SpanTuiTimedStep ("Run {0} x{1}" -f ($Function -join ', '), $Repeat) {
        Push-Location $build
        try {
            for ($run = 1; $run -le $Repeat; ++$run) {
                if ($Repeat -gt 1) { Write-Host "-- run $run of $Repeat" }
                & $functionImage @Function
                if ($LASTEXITCODE -ne 0) { break }
            }
        } finally {
            Pop-Location
        }
    }
} else {
    # Tests run in parallel: each has its own scratch directories, and most of
    # a test's time is spent waiting on child processes and timers.
    $parallel = if ($Jobs -gt 0) { $Jobs } else { [Environment]::ProcessorCount }
    $ctestArgs = @('--test-dir', $build, '--output-on-failure', '--parallel', "$parallel") + $selector
    if ($Repeat -gt 1) { $ctestArgs += @('--repeat', "until-fail:$Repeat") }
    Invoke-SpanTuiTimedStep ("Run {0} test(s)" -f $tests.Count) {
        & $toolchain.CTest @ctestArgs
    }
}
$testExit = $LASTEXITCODE

if ($Coverage) {
    # First-party sources only; exception and unreachable branches are noise
    # gcov adds to every C++ call.
    $report = Join-Path $build 'report'
    if (Test-Path -LiteralPath $report) { Remove-Item -LiteralPath $report -Recurse -Force }
    New-Item -ItemType Directory -Path $report | Out-Null
    $summary = Join-Path $report 'summary.json'
    # gcovr splits --gcov-executable like a POSIX shell, so backslashes must go.
    $gcov = (Join-Path (Split-Path -Parent $toolchain.Compiler) 'gcov.exe') -replace '\\', '/'
    # Filters are paths relative to the working directory: the source root.
    Invoke-SpanTuiTimedStep 'Coverage report' {
        Push-Location $root
        try {
            & $gcovr --root $root --object-directory $build --gcov-executable $gcov `
                --filter 'src/' --exclude 'src/terminal/vendor/' `
                --exclude-throw-branches --exclude-unreachable-branches --gcov-ignore-errors all -j `
                --json-summary $summary --html-nested (Join-Path $report 'index.html')
        } finally {
            Pop-Location
        }
        if ($LASTEXITCODE -ne 0) { Fail 'gcovr could not produce the coverage report.' }
    }
    # One row per layer: the library directories under src\, with the
    # executable's composition root (application\runtime, main.cpp) apart.
    $layers = [ordered]@{}
    foreach ($file in (Get-Content -LiteralPath $summary -Raw | ConvertFrom-Json).files) {
        $path = ([string]$file.filename) -replace '\\', '/'
        $layer = if ($path -match '^src/application/runtime/') { 'application/runtime' }
                 elseif ($path -match '^src/([^/]+)/') { $Matches[1] } else { 'main' }
        if (-not $layers.Contains($layer)) { $layers[$layer] = [int[]]@(0, 0, 0, 0, 0, 0) }
        $totals = $layers[$layer]
        $totals[0] += $file.line_covered; $totals[1] += $file.line_total
        $totals[2] += $file.branch_covered; $totals[3] += $file.branch_total
        $totals[4] += $file.function_covered; $totals[5] += $file.function_total
    }
    $percent = { param($covered, $total) if ($total -gt 0) { '{0,6:n1}%' -f (100.0 * $covered / $total) } else { '     -' } }
    $all = [int[]]@(0, 0, 0, 0, 0, 0)
    $rows = @(('{0,-22} {1,8} {2,7} {3,8} {4,7} {5,8}' -f 'layer', 'lines', '', 'branches', '', 'functions'))
    foreach ($name in ($layers.Keys | Sort-Object)) {
        $t = $layers[$name]
        for ($k = 0; $k -lt 6; ++$k) { $all[$k] += $t[$k] }
        $rows += ('{0,-22} {1} {2,7} {3} {4,7} {5}' -f $name, (& $percent $t[0] $t[1]), $t[1],
                  (& $percent $t[2] $t[3]), $t[3], (& $percent $t[4] $t[5]))
    }
    $rows += ('{0,-22} {1} {2,7} {3} {4,7} {5}' -f 'total', (& $percent $all[0] $all[1]), $all[1],
              (& $percent $all[2] $all[3]), $all[3], (& $percent $all[4] $all[5]))
    $rows | Set-Content -LiteralPath (Join-Path $report 'layers.txt') -Encoding utf8
    $rows | ForEach-Object { Write-Host $_ }
    Write-Host "Coverage report: $(Join-Path $report 'index.html')"
}

if ($testExit -ne 0) {
    Write-Host 'TEST_FAIL' -ForegroundColor Red
    exit $testExit
}
Write-Host 'TEST_OK'
